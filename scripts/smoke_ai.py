"""Real AI smoke test against a running BidCopilot site.

Usage:
    cd backend
    BIDCOPILOT_DEMO_PASSWORD='<demo-password>' uv run python ../scripts/smoke_ai.py --base-url http://127.0.0.1:8000

The demo password must be supplied explicitly via --password or the
BIDCOPILOT_DEMO_PASSWORD environment variable; there is no built-in default.

Uses the configured OpenAI-compatible generation and judge models. This makes
paid model calls; it is intentionally not part of the default pytest suite.
"""

import argparse
import os
import sys
import time

import httpx


class SmokeFailure(Exception):
    pass


def _expect(condition: bool, message: str) -> None:
    if not condition:
        raise SmokeFailure(message)


def run(base_url: str, email: str, password: str, project_name: str | None) -> None:
    with httpx.Client(base_url=base_url.rstrip("/"), timeout=240) as client:
        login = client.post("/api/v1/auth/login", json={"email": email, "password": password})
        _expect(login.is_success, f"login: {login.status_code} {login.text[:200]}")
        headers = {"Authorization": f"Bearer {login.json()['access_token']}"}

        status = client.get("/api/v1/system/ai-status", headers=headers)
        _expect(status.is_success, f"ai-status: {status.status_code}")
        ai = status.json()
        _expect(bool(ai["llm"]["configured"]), "main LLM is not configured")
        print(f"llm: {ai['llm']['model']} @ {ai['llm']['host']}")
        print(f"judge: {ai['judge']['model']} @ {ai['judge']['host']}")

        projects = client.get("/api/v1/projects", headers=headers)
        _expect(projects.is_success, f"projects: {projects.status_code}")
        rows = projects.json()
        if project_name:
            matched = [row for row in rows if row["name"] == project_name]
        else:
            matched = rows
        _expect(bool(matched), "no project available")
        project = matched[0]
        project_id = project["id"]

        sections = client.get(f"/api/v1/projects/{project_id}/sections", headers=headers)
        _expect(sections.is_success, f"sections: {sections.status_code}")
        candidates = [row for row in sections.json() if row["section_type"] == "scoring"]
        _expect(bool(candidates), "project has no scoring section to generate")
        section = candidates[0]

        started = time.time()
        generated = client.post(
            f"/api/v1/projects/{project_id}/generate",
            headers=headers,
            json={"mode": "llm", "section_ids": [section["id"]]},
        )
        elapsed = round(time.time() - started, 2)
        _expect(generated.is_success, f"generate: {generated.status_code} {generated.text[:300]}")
        _expect(generated.json()["status"] == "succeeded", "generation did not succeed")
        refreshed = client.get(f"/api/v1/projects/{project_id}/sections", headers=headers).json()
        target = next(row for row in refreshed if row["id"] == section["id"])
        _expect(target["generation_mode"] == "llm", "section was not generated by LLM")
        _expect(bool(target["content_text"].strip()), "generated section is empty")
        print(f"generation ok: {elapsed}s, {len(target['content_text'])} chars")

        started = time.time()
        evaluation = client.post(f"/api/v1/projects/{project_id}/evaluations", headers=headers)
        elapsed = round(time.time() - started, 2)
        _expect(evaluation.status_code == 201, f"evaluation: {evaluation.status_code} {evaluation.text[:300]}")
        body = evaluation.json()
        summary = body["result_json"].get("summary") or {}
        _expect(bool(summary), "evaluation is missing summary")
        print(
            f"evaluation ok: {elapsed}s, model={body.get('model')}, "
            f"score={summary.get('total_score')}/{summary.get('max_score')} "
            f"({summary.get('percentage')}%)"
        )


def main() -> int:
    parser = argparse.ArgumentParser(description="BidCopilot real AI smoke test")
    parser.add_argument("--base-url", default="http://127.0.0.1:8000")
    parser.add_argument("--email", default="demo@example.com")
    parser.add_argument(
        "--password",
        default=os.environ.get("BIDCOPILOT_DEMO_PASSWORD"),
        help="demo tenant password (or set BIDCOPILOT_DEMO_PASSWORD; no built-in default)",
    )
    parser.add_argument("--project", default=None)
    args = parser.parse_args()
    if not args.password:
        print(
            "demo password required: pass --password or set BIDCOPILOT_DEMO_PASSWORD "
            "(no built-in default credential)",
            file=sys.stderr,
        )
        return 2
    try:
        run(args.base_url, args.email, args.password, args.project)
    except (SmokeFailure, httpx.HTTPError) as exc:
        print(f"AI SMOKE FAILED: {exc}", file=sys.stderr)
        return 1
    print("AI SMOKE OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
